// مولّد أرقام حتمي لمسارات المحاكاة في مسارات AI.
// الغرض: مسارات المحاكاة كانت تستخدم Math.random() فتعطي نتائج مختلفة من جواب لآخر
// لنفس المدخل تماماً — ولا يوجد أي عقد سلوكي على هذه القيم (كانت عشوائية أصلاً)،
// والحد الوحيد هو بقاء الفريدية داخل الجواب الواحد والمحافظة على نفس الأنواع.
// بما أن المولّد يُنشأ لكل استدعاء لحامله (داخل handler أو helper محلي) وبذرة ثابتة
// المستوى، فنفس الطلب يعطي دائماً نفس التسلسل: نتائج قابلة للتكرار والاختبار.

/**
 * إنشاء مولّد أرقام عشوائية حتمي (خوارزمية mulberry32) بلا حالة عالمية.
 * يعيد دالة () => number تعطي قيماً في [0, 1) بخطى متسلسلة ثابتة من نفس البذرة.
 * الحالة محفوظة داخل الإغلاق فقط، فالتسلسل يبدأ من جديد مع كل استدعاء لـ createMockRandom.
 */
export function createMockRandom(seed: number): () => number {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
